#!/usr/bin/env python3
"""Packs the web dashboard (hoptics/web) for the firmware, or as one self-contained preview page.

  tools/make_web.py [--out FILE]         -> hoptics/net/hx_web_files.h (gzipped files as C arrays; CI writes it into
                                            the build tree, so it is not kept in git)
  tools/make_web.py --preview out.html   -> one HTML file with the demo data built in
"""
import gzip, hashlib, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
WEB = ROOT / "hoptics" / "web"


def read(name):
    return (WEB / name).read_text(encoding="utf-8")


def app_js():
    return read("core.js") + "\n" + read("app.js")


def preview(out):
    html = read("index.html")
    html = html.replace('<link rel="stylesheet" href="app.css">', "<style>\n" + read("app.css") + "\n</style>")
    js = read("core.js") + "\n" + read("demo.js") + "\n" + read("app.js")
    js = js.replace("</script", "<\\/script")
    html = html.replace('<script src="app.js"></script>', "<script>\n" + js + "\n</script>")
    html = html.replace('id="loginHint">', 'id="loginHint"><b>Demo:</b> any six digits sign you in. Everything on this page is made up. ')
    pathlib.Path(out).write_text(html, encoding="utf-8")
    print("preview:", out, len(html), "bytes")


def firmware(dest=None):
    files = [("/", "index.html", read("index.html"), "text/html; charset=utf-8"),
             ("/app.css", "app.css", read("app.css"), "text/css; charset=utf-8"),
             ("/app.js", "app.js", app_js(), "application/javascript; charset=utf-8")]
    out = ["// Generated by tools/make_web.py from hoptics/web. Do not edit.", "#pragma once", "#include <stddef.h>", "#include <stdint.h>", "",
           "namespace hxweb", "{", "struct File {", "    const char *path, *type, *etag;", "    const uint8_t *gz;", "    size_t len;", "};"]
    total = 0
    for i, (path, name, text, ctype) in enumerate(files):
        gz = gzip.compress(text.encode("utf-8"), compresslevel=9, mtime=0)
        total += len(gz)
        out.append("static const uint8_t f%d[] = {" % i)
        for o in range(0, len(gz), 24):
            out.append("    " + ",".join("0x%02x" % b for b in gz[o:o + 24]) + ",")
        out.append("};")
    out.append("static const File files[] = {")
    for i, (path, name, text, ctype) in enumerate(files):
        etag = hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]
        out.append('    {"%s", "%s", "\\"%s\\"", f%d, sizeof(f%d)},' % (path, ctype, etag, i, i))
    out += ["};", "} // namespace hxweb", ""]
    dest = pathlib.Path(dest) if dest else ROOT / "hoptics" / "net" / "hx_web_files.h"
    dest.write_text("\n".join(out))
    print("firmware:", dest, "gzipped total", total, "bytes")


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--preview":
        preview(sys.argv[2])
    elif len(sys.argv) == 3 and sys.argv[1] == "--out":
        firmware(sys.argv[2])
    else:
        firmware()
