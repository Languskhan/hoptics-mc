#!/usr/bin/env python3
"""Write a C header holding the root certificates the live feed trusts.

Usage: make_roots.py OUT.h NAME PEM [PEM...]
The PEM files come from the Mozilla CA list (Debian's ca-certificates puts them in /etc/ssl/certs).
"""
import subprocess
import sys

out, name, pems = sys.argv[1], sys.argv[2], sys.argv[3:]
lines = ["// Generated by tools/make_roots.py - root CAs trusted for the live feed's HTTPS.", "// clang-format off"]
lines.append("static const char %s[] =" % name)
for path in pems:
    pem = open(path).read().strip()
    subject = subprocess.run(["openssl", "x509", "-noout", "-subject"], input=pem.encode(), capture_output=True).stdout.decode().strip()
    lines.append("    // " + subject.replace("subject=", ""))
    for row in pem.splitlines():
        lines.append('    "%s\\n"' % row)
lines[-1] += ";"
lines.append("// clang-format on")
open(out, "w").write("\n".join(lines) + "\n")
